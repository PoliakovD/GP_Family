using System.Text.RegularExpressions;

namespace FamilyHub.Modules.Medical.Extraction;

/// <summary>
/// Детерминированный фильтр названий ДО платного поиска и до LLM-стражей. Страж легитимности
/// отвечает "нет ли инъекции" и для любого безобидного слова ("Пациент") возвращал уверенность 0.98 —
/// платный запрос уходил по слову из шапки бланка или по обрезанному названию ("Средняя
/// концентрация гемоглобина в", "Тромбоцитарный кри"). Здесь ловится то, что видно без модели:
/// слово из шапки документа и название, оборванное на предлоге/союзе или на дефисе.
/// </summary>
public static class AnalyteNameQuality
{
    /// <summary>Слова шапки/подписи бланка, которые не бывают лабораторным показателем.</summary>
    private static readonly HashSet<string> NotAnalytes = new(StringComparer.OrdinalIgnoreCase)
    {
        "пациент", "пациентка", "врач", "доктор", "фио", "ф.и.о.", "пол", "возраст", "дата", "дата рождения",
        "адрес", "телефон", "полис", "снилс", "паспорт", "направил", "заказ", "отделение", "проба", "материал",
        "биоматериал", "исследование", "показатель", "результат", "значение", "норма", "референс", "единицы",
        "диагноз", "комментарий", "примечание", "лаборатория", "подпись", "исполнитель", "ордер",
    };

    /// <summary>Хвосты, на которых осмысленное название закончиться не может.</summary>
    private static readonly Regex DanglingTail = new(
        @"(?:^|[\s(,])(?:в|во|на|по|с|со|к|ко|от|до|из|за|для|при|над|под|и|или|а|не|без|у|о|об)\s*$|[-–—,:(/]\s*$",
        RegexOptions.IgnoreCase | RegexOptions.Compiled);

    /// <summary>null — название годится; иначе короткая причина по-русски.</summary>
    public static string? RejectReason(string? name)
    {
        var text = name?.Trim();
        if (string.IsNullOrEmpty(text)) return "Пустое название показателя.";

        var letters = text.Count(char.IsLetter);
        if (letters < 2) return "Название показателя слишком короткое.";

        if (NotAnalytes.Contains(text.TrimEnd(':', '.', ' '))) return $"«{text}» — слово из шапки бланка, а не лабораторный показатель.";

        if (DanglingTail.IsMatch(text)) return "Название обрезано на полуслове — похоже на перенос строки в бланке.";

        return null;
    }
}
