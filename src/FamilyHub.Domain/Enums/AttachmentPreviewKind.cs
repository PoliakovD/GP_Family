namespace FamilyHub.Domain.Enums;

/// <summary>
/// Вид сгенерированного превью-артефакта. Модель намеренно минимальна — три вида, а не «набор
/// картинок по одной на страницу» (см. .claude/patterns/frontend_web.md, раздел про вложения):
/// Office сводится к PDF, дальше и PDF, и Office рисует один и тот же клиентский рендерер (pdf.js)
/// по оригиналу/артефакту Pdf, без постраничных JPEG.
/// </summary>
public enum AttachmentPreviewKind
{
    /// <summary>Маленькая картинка для сетки вложений/списка записей — есть у любого готового превью.</summary>
    Thumbnail = 0,

    /// <summary>PDF-артефакт — результат конвертации Office-документа (Gotenberg/LibreOffice).
    /// У вложений, которые и так PDF, этого артефакта нет — вьюер рисует оригинал напрямую.</summary>
    Pdf = 1,

    /// <summary>Нормализованная растровая версия изображения (перекодированный HEIC/TIFF в JPEG) —
    /// то, что реально можно показать в &lt;img&gt;, когда браузер сам формат не понимает.</summary>
    Page = 2,
}
