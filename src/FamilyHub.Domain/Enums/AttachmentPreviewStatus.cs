namespace FamilyHub.Domain.Enums;

/// <summary>Живёт на FileAttachment (не в отдельной job-таблице — в отличие от распознавания,
/// здесь ровно один прогон на вложение, без прогресса по нескольким файлам, отдельная таблица
/// была бы лишним джойном на каждый рендер списка вложений).</summary>
public enum AttachmentPreviewStatus
{
    /// <summary>Ещё не запрашивалось (не путать с Unsupported — этот статус временный, до первой
    /// попытки после загрузки).</summary>
    None = 0,
    Pending = 1,
    Ready = 2,
    Failed = 3,

    /// <summary>Формат в принципе не подразумевает превью (например .doc при выключенном
    /// Gotenberg) — в отличие от Failed, повторная попытка сама по себе ничего не изменит.</summary>
    Unsupported = 4,
}
