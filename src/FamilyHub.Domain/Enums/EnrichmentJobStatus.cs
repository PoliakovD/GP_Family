namespace FamilyHub.Domain.Enums;

/// <summary>Статус конвейера обогащения справочника препаратов (этап 4).</summary>
public enum EnrichmentJobStatus
{
    /// <summary>Поставлена в очередь Hangfire, ожидает обработки.</summary>
    Pending = 0,

    /// <summary>Обрабатывается процессором прямо сейчас.</summary>
    Running = 1,

    /// <summary>Справочник пополнен (или уже содержал препарат на момент повторной проверки).</summary>
    Completed = 2,

    /// <summary>Не удалось найти доверенные источники или пройти антигаллюцинационный гейт — не ретраится.</summary>
    Failed = 3,

    /// <summary>Легаси: "пропущена из-за исчерпанной месячной квоты внешнего поиска" — квота
    /// удалена (ADR-0005 §9, замена вентилем), новым задачам больше не присваивается. Старые
    /// строки со значением 4 в БД остаются как есть (см. Deferred — новый терминал для этого же
    /// класса ситуаций, только "отложена", не "пропущена навсегда").</summary>
    Skipped = 4,

    /// <summary>Платная ветка конвейера отложена, потому что вентиль внешнего поиска закрыт
    /// (см. IWebSearchValveService, ADR-0005 §9) — НЕ терминальный статус, в отличие от Skipped:
    /// задача возобновляется автоматически, как только вентиль открывают
    /// (DeferredEnrichmentReleaseJob). Кэш-хит вентилем не гейтится вовсе, в Deferred уходит
    /// только реальный промах кэша на пути к платному вызову.</summary>
    Deferred = 5,
}
