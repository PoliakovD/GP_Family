namespace FamilyHub.Domain.Enums;

/// <summary>
/// Категории личных медицинских данных, которые взрослый может разрешить читать другому члену
/// семьи (ADR-0017) — например, взрослому ребёнку, наблюдающему за пожилым родителем. Каждый бит
/// независим: можно дать доступ только к приёму лекарств, не открывая дневник. Анализы и визиты сюда
/// не входят — у них своя, более крупная модель шаринга на семью (FamilyMedicalShare/L1+L2, см.
/// MedicalRecordVisibility) — расширять именно её отдельными категориями было бы не нужным дублем.
/// </summary>
[Flags]
public enum HealthShareCategory
{
    None = 0,

    /// <summary>Курсы приёма лекарств и история доз (ADR-0015) — те же данные, что видит наблюдатель
    /// через MedicationWatcher, но грант теперь единственный источник истины о доступе на чтение.</summary>
    Intake = 1,

    /// <summary>График прививок (ADR-0016).</summary>
    Vaccinations = 2,

    /// <summary>Личный дневник самочувствия — до этой фичи был доступен только владельцу (см.
    /// HealthNoteService). Доступ по гранту всегда read-only, свой дневник продолжает вести только
    /// сам человек.</summary>
    Diary = 4,
}
