namespace FamilyHub.Domain.Enums;

/// <summary>Вид согласия субъекта ПДн (задача 2.3).</summary>
public enum ConsentKind
{
    /// <summary>Общее согласие на обработку персональных данных (весь текст документа).</summary>
    PdnConsent = 0,

    /// <summary>
    /// Отдельное явное согласие на обработку специальной категории — сведений о состоянии
    /// здоровья (ч. 2 ст. 10 152-ФЗ). Записывается атомарно вместе с <see cref="PdnConsent"/>
    /// той же версии: на фронтенде это отдельный обязательный чекбокс (ConsentGateComponent),
    /// без которого кнопка «Принять» неактивна — строка в БД служит доказательством, что
    /// пользователь отдельно, а не только «в общем пакете», согласился на медданные.
    /// </summary>
    SpecialCategoryConsent = 1,
}
