/**
 * Фиксированные ориентиры для давления и пульса — поверх «вашего обычного диапазона» в дневнике.
 * Раньше плитка сравнивала значение только с квартилями истории самого пользователя, и стабильные
 * 160/100 назывались «в вашем обычном диапазоне». Это не диагноз: только повод показать «выше/ниже
 * рекомендуемого» вместо успокаивающей формулировки. Пороги — общепринятые для взрослых в покое
 * (АД ≥140/90 — повышенное, <90/60 — пониженное; пульс >100 или <50).
 */
export function vitalsWarning(code: string, value: number, value2: number | null | undefined): string | null {
  if (code === 'blood_pressure') {
    const dia = value2 ?? null;
    if (value >= 140 || (dia !== null && dia >= 90)) return 'выше рекомендуемого (140/90) — обсудите с врачом';
    if (value < 90 || (dia !== null && dia < 60)) return 'ниже рекомендуемого (90/60) — обсудите с врачом';
    return null;
  }
  if (code === 'pulse') {
    if (value > 100) return 'выше 100 уд/мин в покое — обсудите с врачом';
    if (value < 50) return 'ниже 50 уд/мин — обсудите с врачом';
    return null;
  }
  return null;
}
