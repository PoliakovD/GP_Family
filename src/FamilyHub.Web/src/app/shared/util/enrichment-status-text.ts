import { pluralizeRu } from './pluralize';

/**
 * Текст тултипа чипа «уточняем норму…»/«ищем описание препарата…» (§5+живой поток мыслей) —
 * общий для показателей и медикаментов: живая "мысль" модели, если задача реально держит гейт
 * LM Studio прямо сейчас; иначе — сколько задач из ЛЮБОГО из четырёх конвейеров реально стоят
 * впереди в общей очереди к единственной модели (не путать пользователя тем, что задача "висит"
 * без объяснений, пока справочник насыщается или идёт большой поток анализов); иначе — обычный
 * фолбэк "идёт фоновый поиск".
 */
export function enrichmentStatusTitle(liveText: string | null, queueAhead: number, fallback: string): string {
  if (liveText) return liveText;
  if (queueAhead > 0) {
    return `В очереди к модели — ещё ${queueAhead} ${pluralizeRu(queueAhead, 'задача', 'задачи', 'задач')} впереди`;
  }
  return fallback;
}
