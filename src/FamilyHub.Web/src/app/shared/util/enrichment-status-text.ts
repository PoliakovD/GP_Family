import { pluralizeRu } from './pluralize';

/**
 * Текст тултипа чипа «уточняем норму…»/«ищем описание препарата…» (§5 плана «живой конвейер») —
 * общий для показателей и медикаментов: сколько задач из ЛЮБОГО из четырёх конвейеров реально стоят
 * впереди в общей очереди к единственной модели (не путать пользователя тем, что задача "висит" без
 * объяснений, пока справочник насыщается или идёт большой поток анализов); иначе — обычный фолбэк
 * "идёт фоновый поиск".
 */
export function enrichmentStatusTitle(queueAhead: number, fallback: string): string {
  if (queueAhead > 0) {
    return `В очереди к модели — ещё ${queueAhead} ${pluralizeRu(queueAhead, 'задача', 'задачи', 'задач')} впереди`;
  }
  return fallback;
}
