/** Источник показателя (пересборка enrich-пайплайна) — сервер отдаёт готовую строку
 * (specimenDisplayName), никакого локального маппинга enum→подпись на фронте больше нет: и
 * биоматериал ("кровь"), и небиологическое исследование ("ЭКГ") — обычные строки общего
 * справочника (GlobalSpecimenKb). Единственная задача этой функции — фолбэк текста, если ссылка
 * почему-то не разрешилась (не должно случаться в норме). */
export function specimenLabel(displayName: string | null | undefined): string {
  return displayName ?? 'Источник не определён';
}
